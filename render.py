#!/usr/bin/env python3
"""render.py — build each site's CodeBuild buildspec from sites.toml + publish.sh.

This repository IS Organize's deploy code. It lives in organize-org, not in the
contractor's registry, so the pipeline that publishes these three sites can be
read, changed and run by whoever holds the GitHub organisation — with no access
to anything of Coa's. That is the point: the sites do not depend on a central
engine belonging to someone else.

The buildspec lives in the CodeBuild project rather than in each SITE's
repository, so a site repo stays nothing but the site. It is generated from
sites.toml and publish.sh here, and publish.sh goes in verbatim, so the three
sites cannot diverge in how they publish — only in the few lines sites.toml
allows.

  render.py <site>            print the buildspec
  render.py <site> --check    compare it to what the live project holds
  render.py <site> --push     write it to the live project

--check is the one that matters day to day: it is how you find out that someone
edited a buildspec in the console.
"""

import json
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # tomllib is standard from 3.11; macOS still ships 3.9
    sys.exit("render.py needs Python 3.11 or newer (for tomllib); try python3.12 render.py ...")

HERE = Path(__file__).parent
PROJECT = {"opodata": "opodata-site", "costlyeffects": "ord-site",
           "organdonationreform": "odr-site"}
PROFILE = "coa-organdonation-sso"


def buildspec(key: str, cfg: dict) -> str:
    publish = (HERE / "publish.sh").read_text()
    # Indented into a quoted-heredoc so the shell expands nothing inside it: the
    # script reaches the build byte for byte, however it is written.
    body = "\n".join("        " + line if line else "" for line in publish.splitlines())

    env = {
        "SITE": cfg["site"],
        "BUCKET": cfg["bucket"],
        "DIST": cfg["dist"],
        "OUT_DIR": cfg["out_dir"],
        "MIN_PAGES": str(cfg["min_pages"]),
        "PREVIEW_HOST": cfg["preview_host"],
        "REPO": cfg["repo"],
        "KEEP_RELEASES": "20",
        # Set by hand on a project to force a publish from a build that a webhook
        # did not trigger (a manual re-run). Empty means "do what the event says".
        "FORCE_MODE": "",
    }
    vars_block = "\n".join(f'    {k}: "{v}"' for k, v in env.items())
    build_cmds = "\n".join(f"      - {c}" for c in cfg["build"])

    return f"""version: 0.2
# GENERATED by organize-org/infra render.py from sites.toml and publish.sh.
# Do not edit here: an edit in the console is invisible to review and is exactly
# what `render.py {key} --check` is for. Change the source and push it.
#
# Lives in the CodeBuild project rather than in the site's own repository, so a site
# repo stays nothing but the site.
env:
  variables:
{vars_block}
  parameter-store:
    GITHUB_TOKEN: {cfg["github_token"]}
phases:
  install:
    runtime-versions:
      {cfg["runtime"]}: {cfg["runtime_ver"]}
  build:
    on-failure: ABORT
    commands:
{build_cmds}
  post_build:
    commands:
      - |
        cat > /tmp/publish.sh <<'PUBLISH_SH'
{body}
        PUBLISH_SH
        chmod +x /tmp/publish.sh
        SHA=$(echo "$CODEBUILD_RESOLVED_SOURCE_VERSION" | cut -c1-7)
        MODE="${{FORCE_MODE:-$CODEBUILD_WEBHOOK_EVENT}}"
        case "$MODE" in
          PUSH)  /tmp/publish.sh release "$SHA" ;;
          STAGE) /tmp/publish.sh stage   "$SHA" ;;
          *)     /tmp/publish.sh preview "${{CODEBUILD_WEBHOOK_TRIGGER#pr/}}" ;;
        esac
"""


def live(project: str) -> str:
    out = subprocess.run(
        ["aws", "codebuild", "batch-get-projects", "--names", project,
         "--query", "projects[0].source.buildspec", "--output", "text"],
        env={"AWS_PROFILE": PROFILE, "PATH": "/usr/local/bin:/usr/bin:/bin",
             "HOME": str(Path.home())},
        capture_output=True, text=True, check=True)
    return out.stdout


def main() -> int:
    cfg = tomllib.loads((HERE / "sites.toml").read_text())
    key = sys.argv[1] if len(sys.argv) > 1 else ""
    if key not in cfg:
        print(f"usage: render.py <{'|'.join(cfg)}> [--check|--push]", file=sys.stderr)
        return 64

    spec = buildspec(key, cfg[key])
    flag = sys.argv[2] if len(sys.argv) > 2 else ""

    if flag == "--check":
        if live(PROJECT[key]).strip() == spec.strip():
            print(f"{key}: the live buildspec matches the source")
            return 0
        print(f"{key}: THE LIVE BUILDSPEC DOES NOT MATCH ship/ — someone edited the "
              f"project directly, or the source moved on without being pushed", file=sys.stderr)
        return 1

    if flag == "--push":
        subprocess.run(
            ["aws", "codebuild", "update-project", "--name", PROJECT[key],
             "--source", json.dumps({"type": "GITHUB",
                                     "location": f"https://github.com/{cfg[key]['repo']}.git",
                                     "buildspec": spec,
                                     "gitCloneDepth": 1,
                                     "reportBuildStatus": True}),
             "--query", "project.name", "--output", "text"],
            env={"AWS_PROFILE": PROFILE, "PATH": "/usr/local/bin:/usr/bin:/bin",
                 "HOME": str(Path.home())},
            check=True)
        print(f"{key}: pushed to {PROJECT[key]}")
        return 0

    print(spec, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
